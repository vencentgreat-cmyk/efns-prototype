-- Read-only review query. Do not treat results as authority to repair data.
-- Uses the same relationship as the Flock page's Matched Production Records:
-- CORE.PRODUCTION_RECORD.FLOCK_ID = CORE.FLOCK.FLOCK_ID.

WITH matched_flocks AS (
    SELECT DISTINCT p.FLOCK_ID
    FROM EFNS_DEV.CORE.PRODUCTION_RECORD AS p
    WHERE p.FLOCK_ID IS NOT NULL
),
latest_count_day AS (
    SELECT
        ft.FLOCK_ID,
        MAX(ft.TRANSACTION_DATE) AS LATEST_COUNT_DATE
    FROM EFNS_DEV.CORE.FLOCK_TRANSACTION AS ft
    JOIN matched_flocks AS mf
      ON mf.FLOCK_ID = ft.FLOCK_ID
    WHERE ft.TRANSACTION_TYPE = 'Count'
      AND ft.TRANSACTION_DATE <= CONVERT_TIMEZONE(
          'America/Halifax', CURRENT_TIMESTAMP()
      )::DATE
    GROUP BY ft.FLOCK_ID
),
latest_count_rows AS (
    SELECT
        ft.FLOCK_ID,
        ft.TRANSACTION_DATE,
        ft.QUANTITY,
        COALESCE(NULLIF(TRIM(ft.COUNT_SOURCE_LABEL), ''), 'Unknown') AS COUNT_SOURCE,
        ft.FLOCK_TRANSACTION_ID
    FROM EFNS_DEV.CORE.FLOCK_TRANSACTION AS ft
    JOIN latest_count_day AS lcd
      ON lcd.FLOCK_ID = ft.FLOCK_ID
     AND lcd.LATEST_COUNT_DATE = ft.TRANSACTION_DATE
    WHERE ft.TRANSACTION_TYPE = 'Count'
),
latest_count AS (
    SELECT
        FLOCK_ID,
        MAX(TRANSACTION_DATE) AS LATEST_COUNT_DATE,
        IFF(
            COUNT(DISTINCT QUANTITY) > 1
            OR COUNT(DISTINCT COUNT_SOURCE) > 1,
            NULL,
            MAX(QUANTITY)
        ) AS LATEST_COUNT,
        IFF(
            COUNT(DISTINCT QUANTITY) > 1
            OR COUNT(DISTINCT COUNT_SOURCE) > 1,
            'Conflict: ' || LISTAGG(DISTINCT COUNT_SOURCE, ', ')
                WITHIN GROUP (ORDER BY COUNT_SOURCE),
            MAX(COUNT_SOURCE)
        ) AS LATEST_COUNT_SOURCE,
        COUNT(*) AS LATEST_DAY_COUNT_ROWS,
        COUNT(DISTINCT QUANTITY) > 1
          OR COUNT(DISTINCT COUNT_SOURCE) > 1 AS HAS_SAME_DAY_CONFLICT,
        LISTAGG(FLOCK_TRANSACTION_ID, ', ')
            WITHIN GROUP (ORDER BY FLOCK_TRANSACTION_ID) AS SOURCE_TRANSACTION_IDS
    FROM latest_count_rows
    GROUP BY FLOCK_ID
)
SELECT
    f.FLOCK_NUMBER,
    f.FLOCK_ID,
    COUNT(DISTINCT p.PRODUCTION_ID) AS MATCHED_PRODUCTION_RECORDS,
    lc.LATEST_COUNT_DATE,
    lc.LATEST_COUNT,
    lc.LATEST_COUNT_SOURCE,
    COALESCE(lc.HAS_SAME_DAY_CONFLICT, FALSE) AS HAS_SAME_DAY_CONFLICT,
    lc.LATEST_DAY_COUNT_ROWS,
    lc.SOURCE_TRANSACTION_IDS
FROM matched_flocks AS mf
JOIN EFNS_DEV.CORE.FLOCK AS f
  ON f.FLOCK_ID = mf.FLOCK_ID
JOIN EFNS_DEV.CORE.PRODUCTION_RECORD AS p
  ON p.FLOCK_ID = f.FLOCK_ID
LEFT JOIN latest_count AS lc
  ON lc.FLOCK_ID = f.FLOCK_ID
GROUP BY
    f.FLOCK_NUMBER,
    f.FLOCK_ID,
    lc.LATEST_COUNT_DATE,
    lc.LATEST_COUNT,
    lc.LATEST_COUNT_SOURCE,
    lc.HAS_SAME_DAY_CONFLICT,
    lc.LATEST_DAY_COUNT_ROWS,
    lc.SOURCE_TRANSACTION_IDS
ORDER BY f.FLOCK_NUMBER, f.FLOCK_ID;

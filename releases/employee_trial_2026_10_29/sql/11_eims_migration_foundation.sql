-- EFNS DEV / PROVISIONAL historical EIMS migration foundation.
-- Reviewed for EFNS_DEV only. This script does not change operational schemas.

-- SYSADMIN owns the database schemas created by sql/01_setup.sql and creates
-- these DEV objects. SECURITYADMIN applies only the exact runtime grants.
USE ROLE SYSADMIN;

CREATE STAGE IF NOT EXISTS EFNS_DEV.RAW.EIMS_MIGRATION_FILES
    ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
    DIRECTORY = (ENABLE = TRUE)
    COMMENT = 'Encrypted internal stage for provisional EIMS migration packages';

CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.MIGRATION_BATCH (
    MIGRATION_BATCH_ID VARCHAR(64) NOT NULL,
    PACKAGE_HASH VARCHAR(64) NOT NULL,
    SCHEMA_VERSION VARCHAR(100) NOT NULL,
    STATUS VARCHAR(30) NOT NULL,
    SOURCE_FILE_COUNT NUMBER(10,0) NOT NULL,
    SOURCE_ROW_COUNT NUMBER(18,0) NOT NULL,
    READY_ROW_COUNT NUMBER(18,0) NOT NULL,
    REJECTED_ROW_COUNT NUMBER(18,0) NOT NULL,
    CREATED_BY VARCHAR(255),
    COMMITTED_AT TIMESTAMP_NTZ,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_MIGRATION_BATCH PRIMARY KEY (MIGRATION_BATCH_ID),
    CONSTRAINT UQ_MIGRATION_BATCH_HASH UNIQUE (PACKAGE_HASH)
);

CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.MIGRATION_FILE (
    MIGRATION_FILE_ID VARCHAR(36) NOT NULL,
    MIGRATION_BATCH_ID VARCHAR(64) NOT NULL,
    SOURCE_FILENAME VARCHAR(500) NOT NULL,
    SOURCE_ENTITY VARCHAR(100) NOT NULL,
    FILE_HASH VARCHAR(64) NOT NULL,
    FILE_SIZE_BYTES NUMBER(18,0),
    SOURCE_ROW_COUNT NUMBER(18,0),
    STAGE_PATH VARCHAR(1000),
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_MIGRATION_FILE PRIMARY KEY (MIGRATION_FILE_ID),
    CONSTRAINT FK_MIGRATION_FILE_BATCH FOREIGN KEY (MIGRATION_BATCH_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_BATCH (MIGRATION_BATCH_ID)
);

CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.MIGRATION_RAW_ROW (
    MIGRATION_RAW_ROW_ID VARCHAR(64) NOT NULL,
    MIGRATION_BATCH_ID VARCHAR(64) NOT NULL,
    SOURCE_FILENAME VARCHAR(500) NOT NULL,
    SOURCE_ENTITY VARCHAR(100) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER(18,0) NOT NULL,
    SOURCE_ID VARCHAR(255),
    TARGET_ID VARCHAR(255),
    RAW_DATA VARIANT NOT NULL,
    NORMALIZED_DATA VARIANT,
    VALIDATION_STATUS VARCHAR(30) NOT NULL,
    MATCH_STATUS VARCHAR(30),
    VALIDATION_MESSAGES VARIANT,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_MIGRATION_RAW_ROW PRIMARY KEY (MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID),
    CONSTRAINT FK_MIGRATION_RAW_ROW_BATCH FOREIGN KEY (MIGRATION_BATCH_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_BATCH (MIGRATION_BATCH_ID)
);

CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.MIGRATION_ID_MAP (
    MIGRATION_ID_MAP_ID VARCHAR(36) NOT NULL,
    MIGRATION_RAW_ROW_ID VARCHAR(64) NOT NULL,
    MIGRATION_BATCH_ID VARCHAR(64) NOT NULL,
    SOURCE_ENTITY VARCHAR(100) NOT NULL,
    SOURCE_ID VARCHAR(255) NOT NULL,
    TARGET_ID VARCHAR(255) NOT NULL,
    STATUS VARCHAR(30) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_MIGRATION_ID_MAP PRIMARY KEY (MIGRATION_ID_MAP_ID),
    CONSTRAINT FK_MIGRATION_ID_MAP_BATCH FOREIGN KEY (MIGRATION_BATCH_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_BATCH (MIGRATION_BATCH_ID),
    CONSTRAINT UQ_MIGRATION_SOURCE_ROW UNIQUE (MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID),
    CONSTRAINT FK_MIGRATION_ID_MAP_RAW_ROW FOREIGN KEY (MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_RAW_ROW (MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID)
);

CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.MIGRATION_ERROR (
    MIGRATION_ERROR_ID VARCHAR(36) NOT NULL,
    MIGRATION_BATCH_ID VARCHAR(64) NOT NULL,
    SOURCE_FILENAME VARCHAR(500) NOT NULL,
    SOURCE_ENTITY VARCHAR(100) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER(18,0) NOT NULL,
    FIELD_NAME VARCHAR(255),
    ERROR_CATEGORY VARCHAR(100) DEFAULT 'VALIDATION',
    ERROR_MESSAGE VARCHAR(2000) NOT NULL,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_MIGRATION_ERROR PRIMARY KEY (MIGRATION_ERROR_ID),
    CONSTRAINT FK_MIGRATION_ERROR_BATCH FOREIGN KEY (MIGRATION_BATCH_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_BATCH (MIGRATION_BATCH_ID)
);

CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.MIGRATION_RECONCILIATION (
    MIGRATION_RECONCILIATION_ID VARCHAR(36) NOT NULL,
    MIGRATION_BATCH_ID VARCHAR(64) NOT NULL,
    SOURCE_ENTITY VARCHAR(100) NOT NULL,
    SOURCE_ROWS NUMBER(18,0) NOT NULL,
    READY_ROWS NUMBER(18,0) NOT NULL,
    REJECTED_ROWS NUMBER(18,0) NOT NULL,
    INSERTED_ROWS NUMBER(18,0) NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_MIGRATION_RECONCILIATION PRIMARY KEY (MIGRATION_RECONCILIATION_ID),
    CONSTRAINT FK_MIGRATION_RECONCILIATION_BATCH FOREIGN KEY (MIGRATION_BATCH_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_BATCH (MIGRATION_BATCH_ID),
    CONSTRAINT UQ_MIGRATION_RECONCILIATION UNIQUE (MIGRATION_BATCH_ID, SOURCE_ENTITY)
);

USE ROLE SECURITYADMIN;

GRANT READ, WRITE ON STAGE EFNS_DEV.RAW.EIMS_MIGRATION_FILES TO ROLE EFNS_DEV_APP_OWNER;
GRANT SELECT, INSERT, UPDATE ON TABLE EFNS_DEV.RAW.MIGRATION_BATCH TO ROLE EFNS_DEV_APP_OWNER;
GRANT SELECT, INSERT ON TABLE EFNS_DEV.RAW.MIGRATION_FILE TO ROLE EFNS_DEV_APP_OWNER;
GRANT SELECT, INSERT ON TABLE EFNS_DEV.RAW.MIGRATION_RAW_ROW TO ROLE EFNS_DEV_APP_OWNER;
GRANT SELECT, INSERT, UPDATE ON TABLE EFNS_DEV.RAW.MIGRATION_ID_MAP TO ROLE EFNS_DEV_APP_OWNER;
GRANT SELECT, INSERT ON TABLE EFNS_DEV.RAW.MIGRATION_ERROR TO ROLE EFNS_DEV_APP_OWNER;
GRANT SELECT, INSERT, UPDATE ON TABLE EFNS_DEV.RAW.MIGRATION_RECONCILIATION TO ROLE EFNS_DEV_APP_OWNER;
GRANT SELECT, INSERT, DELETE ON TABLE EFNS_DEV.CORE.SALMONELLA_TEST_SAMPLE TO ROLE EFNS_DEV_APP_OWNER;

-- Existing EFNS_DEV business tables are owned by ACCOUNTADMIN in the current
-- DEV account. Keep the legacy signature/grants, but block prefix-only cleanup:
-- the real historical batch uses the same DEV_MIGRATION_ namespace.
USE ROLE ACCOUNTADMIN;

CREATE OR REPLACE PROCEDURE EFNS_DEV.RAW.CLEANUP_SYNTHETIC_MIGRATION(BATCH_ID VARCHAR)
COPY GRANTS
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
    -- Real Jensen batches use the same prefix as generated batches. A prefix
    -- alone cannot authorize deletion or prove targets are not shared.
    RETURN 'REJECTED_MANUAL_PROVENANCE_REVIEW_REQUIRED';
END;
$$;

USE ROLE SECURITYADMIN;
GRANT USAGE ON PROCEDURE EFNS_DEV.RAW.CLEANUP_SYNTHETIC_MIGRATION(VARCHAR)
    TO ROLE EFNS_DEV_APP_OWNER;

-- No ordinary EFNS viewer/editor/admin/developer role receives stage or table access.

SELECT STATUS, COUNT(*) AS BATCH_COUNT
FROM EFNS_DEV.RAW.MIGRATION_BATCH
GROUP BY STATUS
ORDER BY STATUS;

SELECT COUNT(*) AS ORPHAN_RAW_ROWS
FROM EFNS_DEV.RAW.MIGRATION_RAW_ROW r
LEFT JOIN EFNS_DEV.RAW.MIGRATION_BATCH b
  ON b.MIGRATION_BATCH_ID = r.MIGRATION_BATCH_ID
WHERE b.MIGRATION_BATCH_ID IS NULL;

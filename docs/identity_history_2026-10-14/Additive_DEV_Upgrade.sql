-- Additive DEV upgrade. No source/business rows are changed by this script.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE EFNS_DEV_WH;
USE DATABASE EFNS_DEV;
EXECUTE IMMEDIATE $$
DECLARE wrong_environment EXCEPTION (-20001, 'Expected original EFNS DEV account');
BEGIN
 IF (CURRENT_DATABASE() <> 'EFNS_DEV' OR CURRENT_ACCOUNT_NAME() <> 'RC34234') THEN
  RAISE wrong_environment;
 END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.INTAKE_LOCK (
 LOCK_ID VARCHAR(100) NOT NULL PRIMARY KEY,
 VERSION NUMBER(38,0) NOT NULL
);
INSERT INTO EFNS_DEV.RAW.INTAKE_LOCK (LOCK_ID,VERSION)
SELECT 'continuity',0 WHERE NOT EXISTS
 (SELECT 1 FROM EFNS_DEV.RAW.INTAKE_LOCK WHERE LOCK_ID='continuity');

CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.SOURCE_FILE (
 SOURCE_FILE_ID VARCHAR(36) NOT NULL PRIMARY KEY,
 ORIGINAL_FILENAME VARCHAR(1000) NOT NULL,
 FILE_HASH VARCHAR(64) NOT NULL,
 FILE_SIZE_BYTES NUMBER(38,0) NOT NULL,
 STAGE_PATH VARCHAR(2000) NOT NULL,
 IMPORT_ROUTE VARCHAR(100) NOT NULL,
 PARSE_STATUS VARCHAR(50) NOT NULL,
 PARSE_ERROR VARCHAR(2000),
 UPLOADED_BY VARCHAR(100),
 UPLOADED_AT TIMESTAMP_NTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.PRODUCTION_MATCH_DECISION (
 MATCH_DECISION_ID VARCHAR(36) NOT NULL PRIMARY KEY,
 PRODUCTION_ID VARCHAR(36) NOT NULL REFERENCES EFNS_DEV.CORE.PRODUCTION_RECORD(PRODUCTION_ID),
 SOURCE_FILE_ID VARCHAR(36) REFERENCES EFNS_DEV.RAW.SOURCE_FILE(SOURCE_FILE_ID),
 RAW_ROW_ID VARCHAR(36),
 SOURCE_PRODUCER_NUMBER VARCHAR(100),
 ACCOUNT_ID VARCHAR(36) REFERENCES EFNS_DEV.CORE.ACCOUNT(ACCOUNT_ID),
 MATCH_STATUS VARCHAR(50) NOT NULL,
 MATCH_METHOD VARCHAR(100) NOT NULL,
 MATCH_BASIS VARCHAR(2000) NOT NULL,
 HANDLING VARCHAR(50) NOT NULL,
 RECORDED_BY VARCHAR(100),
 RECORDED_AT TIMESTAMP_NTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS EFNS_DEV.CORE.FLOCK_EVENT (
 EVENT_ID VARCHAR(36) NOT NULL PRIMARY KEY,
 FLOCK_ID VARCHAR(36) NOT NULL REFERENCES EFNS_DEV.CORE.FLOCK(FLOCK_ID),
 EVENT_TYPE VARCHAR(50) NOT NULL,
 FROM_FACILITY_ID VARCHAR(36) REFERENCES EFNS_DEV.CORE.FACILITY(FACILITY_ID),
 TO_FACILITY_ID VARCHAR(36) REFERENCES EFNS_DEV.CORE.FACILITY(FACILITY_ID),
 EFFECTIVE_AT TIMESTAMP_NTZ NOT NULL,
 RECORDED_AT TIMESTAMP_NTZ NOT NULL,
 RECORDED_BY VARCHAR(100) NOT NULL,
 REASON VARCHAR(2000) NOT NULL,
 SUPERSEDES_EVENT_ID VARCHAR(36) REFERENCES EFNS_DEV.CORE.FLOCK_EVENT(EVENT_ID),
 BEFORE_DATA VARIANT NOT NULL,
 AFTER_DATA VARIANT NOT NULL
);
CREATE TABLE IF NOT EXISTS EFNS_DEV.APP.RECORD_REVISION (
 REVISION_ID VARCHAR(36) NOT NULL PRIMARY KEY,
 ENTITY_TYPE VARCHAR(50) NOT NULL,
 ENTITY_ID VARCHAR(1000) NOT NULL,
 CHANGE_KIND VARCHAR(50) NOT NULL,
 BUSINESS_AT TIMESTAMP_NTZ,
 RECORDED_AT TIMESTAMP_NTZ NOT NULL,
 RECORDED_BY VARCHAR(100) NOT NULL,
 REASON VARCHAR(2000) NOT NULL,
 BEFORE_DATA VARIANT NOT NULL,
 AFTER_DATA VARIANT NOT NULL
);
ALTER TABLE IF EXISTS EFNS_DEV.RAW.IMPORT_BATCH ADD COLUMN IF NOT EXISTS SOURCE_FILE_ID VARCHAR(36);
ALTER TABLE IF EXISTS EFNS_DEV.RAW.IMPORT_RAW_ROW ADD COLUMN IF NOT EXISTS SOURCE_FILE_ID VARCHAR(36);
ALTER TABLE IF EXISTS EFNS_DEV.RAW.IMPORT_RAW_ROW ADD COLUMN IF NOT EXISTS TARGET_ENTITY VARCHAR(50);
ALTER TABLE IF EXISTS EFNS_DEV.RAW.IMPORT_RAW_ROW ADD COLUMN IF NOT EXISTS TARGET_ID VARCHAR(36);
ALTER TABLE IF EXISTS EFNS_DEV.CORE.PRODUCTION_RECORD ADD COLUMN IF NOT EXISTS SOURCE_FILE_ID VARCHAR(36);
ALTER TABLE IF EXISTS EFNS_DEV.CORE.PRODUCTION_RECORD ADD COLUMN IF NOT EXISTS RAW_ROW_ID VARCHAR(36);
ALTER TABLE IF EXISTS EFNS_DEV.CORE.PRODUCTION_RECORD ADD COLUMN IF NOT EXISTS MATCH_METHOD VARCHAR(100);
ALTER TABLE IF EXISTS EFNS_DEV.CORE.PRODUCTION_RECORD ADD COLUMN IF NOT EXISTS MATCH_BASIS VARCHAR(2000);
-- Match/source references are checked by the writer. No inferred historical FK.
GRANT SELECT,INSERT,UPDATE ON TABLE EFNS_DEV.RAW.SOURCE_FILE TO ROLE EFNS_DEV_DEPLOYER;
GRANT SELECT,UPDATE ON TABLE EFNS_DEV.RAW.INTAKE_LOCK TO ROLE EFNS_DEV_DEPLOYER;
GRANT SELECT,INSERT ON TABLE EFNS_DEV.RAW.PRODUCTION_MATCH_DECISION TO ROLE EFNS_DEV_DEPLOYER;
GRANT SELECT,INSERT ON TABLE EFNS_DEV.CORE.FLOCK_EVENT TO ROLE EFNS_DEV_DEPLOYER;
GRANT SELECT,INSERT ON TABLE EFNS_DEV.APP.RECORD_REVISION TO ROLE EFNS_DEV_DEPLOYER;
GRANT UPDATE ON TABLE EFNS_DEV.CORE.PRODUCTION_RECORD TO ROLE EFNS_DEV_DEPLOYER;
GRANT UPDATE ON TABLE EFNS_DEV.CORE.FLOCK TO ROLE EFNS_DEV_DEPLOYER;
GRANT UPDATE ON TABLE EFNS_DEV.CORE.FACILITY TO ROLE EFNS_DEV_DEPLOYER;
GRANT READ,WRITE ON STAGE EFNS_DEV.RAW.EIMS_MIGRATION_FILES TO ROLE EFNS_DEV_DEPLOYER;

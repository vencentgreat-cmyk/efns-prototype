USE ROLE EFNS_DEV_DEPLOYER;

SET EFNS_INITIAL_ADMIN_EMAIL = 'database@nsegg.ca';
SET EFNS_INITIAL_ADMIN_NAME = 'EFNS Database Admin';

INSERT INTO EFNS_DEV.SECURITY.APP_USER
    (USER_ID, EMAIL, DISPLAY_NAME, ROLE, ACTIVE, CREATED_AT, UPDATED_AT)
SELECT UUID_STRING(),
       LOWER(TRIM($EFNS_INITIAL_ADMIN_EMAIL)),
       TRIM($EFNS_INITIAL_ADMIN_NAME),
       'Admin',
       TRUE,
       CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP()),
       CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())
WHERE LOWER(TRIM($EFNS_INITIAL_ADMIN_EMAIL)) LIKE '%@nsegg.ca'
  AND NOT EXISTS (
      SELECT 1
      FROM EFNS_DEV.SECURITY.APP_USER
      WHERE LOWER(EMAIL) = LOWER(TRIM($EFNS_INITIAL_ADMIN_EMAIL))
  );

SELECT EMAIL, DISPLAY_NAME, ROLE, ACTIVE
FROM EFNS_DEV.SECURITY.APP_USER
WHERE LOWER(TRIM(EMAIL)) = 'database@nsegg.ca';
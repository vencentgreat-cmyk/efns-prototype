-- DEV-only compatible source identity repair. No RAW payloads are changed.
-- Run while migration/correction writers are idle. Snowflake DDL auto-commits.
-- Save GET_DDL and ID_MAP before running; see docs/eims_source_identity.md.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE EFNS_DEV_WH;
USE DATABASE EFNS_DEV;

EXECUTE IMMEDIATE $$
DECLARE
    UNSAFE_IDENTITY EXCEPTION (-20014, 'Source identity preflight failed. No key repair was applied.');
BEGIN
    IF (CURRENT_DATABASE() <> 'EFNS_DEV') THEN
        RAISE UNSAFE_IDENTITY;
    END IF;
    IF (EXISTS (
        SELECT 1 FROM EFNS_DEV.RAW.MIGRATION_RAW_ROW
        GROUP BY MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID
        HAVING COUNT(*) > 1
    )) THEN
        RAISE UNSAFE_IDENTITY;
    END IF;
    IF (EXISTS (
        SELECT 1 FROM EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW c
        LEFT JOIN EFNS_DEV.RAW.MIGRATION_RAW_ROW r
          ON r.MIGRATION_BATCH_ID = c.ORIGINAL_MIGRATION_BATCH_ID
         AND r.MIGRATION_RAW_ROW_ID = c.MIGRATION_RAW_ROW_ID
        WHERE r.MIGRATION_RAW_ROW_ID IS NULL
           OR c.SOURCE_FILENAME <> r.SOURCE_FILENAME
           OR c.SOURCE_ENTITY <> r.SOURCE_ENTITY
           OR c.SOURCE_ROW_NUMBER <> r.SOURCE_ROW_NUMBER
           OR c.SOURCE_ID IS DISTINCT FROM r.SOURCE_ID
    )) THEN
        RAISE UNSAFE_IDENTITY;
    END IF;
    -- Old map records did not record the specific source row for equal DAYs.
    -- Only equal-sized source/target equivalence groups may be paired.
    IF (EXISTS (
        SELECT 1 FROM (
            SELECT MIGRATION_BATCH_ID, SOURCE_ENTITY, SOURCE_ID, TARGET_ID, COUNT(*) n
            FROM EFNS_DEV.RAW.MIGRATION_ID_MAP GROUP BY 1,2,3,4
        ) m FULL OUTER JOIN (
            SELECT MIGRATION_BATCH_ID, SOURCE_ENTITY, SOURCE_ID, TARGET_ID, COUNT(*) n
            FROM EFNS_DEV.RAW.MIGRATION_RAW_ROW
            WHERE VALIDATION_STATUS = 'READY' AND TARGET_ID IS NOT NULL
            GROUP BY 1,2,3,4
        ) r ON m.MIGRATION_BATCH_ID = r.MIGRATION_BATCH_ID
           AND m.SOURCE_ENTITY = r.SOURCE_ENTITY
           AND m.SOURCE_ID IS NOT DISTINCT FROM r.SOURCE_ID
           AND m.TARGET_ID = r.TARGET_ID
        WHERE m.n IS DISTINCT FROM r.n
    )) THEN
        RAISE UNSAFE_IDENTITY;
    END IF;
END;
$$;

ALTER TABLE EFNS_DEV.RAW.MIGRATION_ID_MAP
    ADD COLUMN IF NOT EXISTS MIGRATION_RAW_ROW_ID VARCHAR(64);

-- Canonical pairing restores source-row granularity, not a lost historical
-- UUID-to-row ordering. UUIDs, source/target values, timestamps and RAW stay intact.
BEGIN TRANSACTION;
UPDATE EFNS_DEV.RAW.MIGRATION_ID_MAP target
SET MIGRATION_RAW_ROW_ID = matched.MIGRATION_RAW_ROW_ID
FROM (
    SELECT m.MIGRATION_ID_MAP_ID, r.MIGRATION_RAW_ROW_ID
    FROM (
        SELECT *, ROW_NUMBER() OVER (
            PARTITION BY MIGRATION_BATCH_ID, SOURCE_ENTITY, SOURCE_ID, TARGET_ID
            ORDER BY MIGRATION_ID_MAP_ID
        ) ordinal
        FROM EFNS_DEV.RAW.MIGRATION_ID_MAP
        WHERE MIGRATION_RAW_ROW_ID IS NULL
    ) m JOIN (
        SELECT *, ROW_NUMBER() OVER (
            PARTITION BY MIGRATION_BATCH_ID, SOURCE_ENTITY, SOURCE_ID, TARGET_ID
            ORDER BY SOURCE_FILENAME, SOURCE_ROW_NUMBER, MIGRATION_RAW_ROW_ID
        ) ordinal
        FROM EFNS_DEV.RAW.MIGRATION_RAW_ROW source_row
        WHERE VALIDATION_STATUS = 'READY' AND TARGET_ID IS NOT NULL
          AND NOT EXISTS (
              SELECT 1 FROM EFNS_DEV.RAW.MIGRATION_ID_MAP assigned
              WHERE assigned.MIGRATION_BATCH_ID = source_row.MIGRATION_BATCH_ID
                AND assigned.MIGRATION_RAW_ROW_ID = source_row.MIGRATION_RAW_ROW_ID
          )
    ) r ON m.MIGRATION_BATCH_ID = r.MIGRATION_BATCH_ID
       AND m.SOURCE_ENTITY = r.SOURCE_ENTITY
       AND m.SOURCE_ID IS NOT DISTINCT FROM r.SOURCE_ID
       AND m.TARGET_ID = r.TARGET_ID AND m.ordinal = r.ordinal
) matched
WHERE target.MIGRATION_ID_MAP_ID = matched.MIGRATION_ID_MAP_ID
  AND target.MIGRATION_RAW_ROW_ID IS NULL;
COMMIT;

EXECUTE IMMEDIATE $$
DECLARE
    INVALID_MAPPING EXCEPTION (-20015, 'Source identity validation failed. Key replacement stopped.');
BEGIN
    IF (EXISTS (
        SELECT 1 FROM EFNS_DEV.RAW.MIGRATION_ID_MAP m
        LEFT JOIN EFNS_DEV.RAW.MIGRATION_RAW_ROW r
          ON r.MIGRATION_BATCH_ID = m.MIGRATION_BATCH_ID
         AND r.MIGRATION_RAW_ROW_ID = m.MIGRATION_RAW_ROW_ID
        WHERE r.MIGRATION_RAW_ROW_ID IS NULL OR r.VALIDATION_STATUS <> 'READY'
           OR m.SOURCE_ENTITY <> r.SOURCE_ENTITY
           OR m.SOURCE_ID IS DISTINCT FROM r.SOURCE_ID
           OR m.TARGET_ID IS DISTINCT FROM r.TARGET_ID
    ) OR EXISTS (
        SELECT 1 FROM EFNS_DEV.RAW.MIGRATION_ID_MAP
        GROUP BY MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID HAVING COUNT(*) > 1
    )) THEN
        RAISE INVALID_MAPPING;
    END IF;
    -- Remove dependent FK before replacing the referenced PK.
    IF (EXISTS (SELECT 1 FROM EFNS_DEV.INFORMATION_SCHEMA.TABLE_CONSTRAINTS
        WHERE TABLE_SCHEMA='RAW' AND TABLE_NAME='MIGRATION_CORRECTION_ROW'
          AND CONSTRAINT_NAME='FK_MIGRATION_CORRECTION_RAW_ROW')) THEN
        ALTER TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW DROP CONSTRAINT FK_MIGRATION_CORRECTION_RAW_ROW;
    END IF;
    IF (EXISTS (SELECT 1 FROM EFNS_DEV.INFORMATION_SCHEMA.TABLE_CONSTRAINTS
        WHERE TABLE_SCHEMA='RAW' AND TABLE_NAME='MIGRATION_ID_MAP'
          AND CONSTRAINT_NAME='FK_MIGRATION_ID_MAP_RAW_ROW')) THEN
        ALTER TABLE EFNS_DEV.RAW.MIGRATION_ID_MAP DROP CONSTRAINT FK_MIGRATION_ID_MAP_RAW_ROW;
    END IF;
    IF (EXISTS (SELECT 1 FROM EFNS_DEV.INFORMATION_SCHEMA.TABLE_CONSTRAINTS
        WHERE TABLE_SCHEMA='RAW' AND TABLE_NAME='MIGRATION_RAW_ROW'
          AND CONSTRAINT_NAME='PK_MIGRATION_RAW_ROW')) THEN
        ALTER TABLE EFNS_DEV.RAW.MIGRATION_RAW_ROW DROP CONSTRAINT PK_MIGRATION_RAW_ROW;
    END IF;
    ALTER TABLE EFNS_DEV.RAW.MIGRATION_RAW_ROW ADD CONSTRAINT PK_MIGRATION_RAW_ROW
        PRIMARY KEY (MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID);
    ALTER TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW ADD CONSTRAINT FK_MIGRATION_CORRECTION_RAW_ROW
        FOREIGN KEY (ORIGINAL_MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_RAW_ROW (MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID);
    ALTER TABLE EFNS_DEV.RAW.MIGRATION_ID_MAP ADD CONSTRAINT FK_MIGRATION_ID_MAP_RAW_ROW
        FOREIGN KEY (MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_RAW_ROW (MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID);
    IF (EXISTS (SELECT 1 FROM EFNS_DEV.INFORMATION_SCHEMA.TABLE_CONSTRAINTS
        WHERE TABLE_SCHEMA='RAW' AND TABLE_NAME='MIGRATION_ID_MAP'
          AND CONSTRAINT_NAME='UQ_MIGRATION_SOURCE_ID')) THEN
        ALTER TABLE EFNS_DEV.RAW.MIGRATION_ID_MAP DROP CONSTRAINT UQ_MIGRATION_SOURCE_ID;
    END IF;
    IF (NOT EXISTS (SELECT 1 FROM EFNS_DEV.INFORMATION_SCHEMA.TABLE_CONSTRAINTS
        WHERE TABLE_SCHEMA='RAW' AND TABLE_NAME='MIGRATION_ID_MAP'
          AND CONSTRAINT_NAME='UQ_MIGRATION_SOURCE_ROW')) THEN
        ALTER TABLE EFNS_DEV.RAW.MIGRATION_ID_MAP ADD CONSTRAINT UQ_MIGRATION_SOURCE_ROW
            UNIQUE (MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID);
    END IF;
    ALTER TABLE EFNS_DEV.RAW.MIGRATION_ID_MAP ALTER COLUMN MIGRATION_RAW_ROW_ID SET NOT NULL;
END;
$$;

SELECT MIGRATION_BATCH_ID, SOURCE_ENTITY, COUNT(*) SOURCE_LINEAGES,
       COUNT(DISTINCT TARGET_ID) DISTINCT_TARGETS
FROM EFNS_DEV.RAW.MIGRATION_ID_MAP GROUP BY 1,2 ORDER BY 1,2;
SHOW PRIMARY KEYS IN TABLE EFNS_DEV.RAW.MIGRATION_RAW_ROW;
SHOW IMPORTED KEYS IN TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW;
SHOW IMPORTED KEYS IN TABLE EFNS_DEV.RAW.MIGRATION_ID_MAP;

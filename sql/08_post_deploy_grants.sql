-- Run after `snow streamlit deploy efns_dev --replace --prune` succeeds.
-- Application roles remain authoritative in SECURITY.APP_USER; these account
-- roles only allow a signed-in Snowflake user to open the Streamlit object.

-- The CLI project definition selects warehouse runtime during creation, and
-- this post-deploy guard makes the choice explicit after every replacement.
USE ROLE EFNS_DEV_DEPLOYER;

ALTER STREAMLIT EFNS_DEV.APP.EFNS_INTERNAL_APP
    SET RUNTIME_NAME = 'SYSTEM$WAREHOUSE_RUNTIME';

USE ROLE SECURITYADMIN;

-- Streamlit executes with its owner role. EFNS_DEV_DEPLOYER inherits the
-- application owner role, which needs the child-table write used by migration.
GRANT SELECT, INSERT, DELETE ON TABLE EFNS_DEV.CORE.SALMONELLA_TEST_SAMPLE
    TO ROLE EFNS_DEV_APP_OWNER;
GRANT SELECT, INSERT, UPDATE ON TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_BATCH
    TO ROLE EFNS_DEV_APP_OWNER;
GRANT SELECT, INSERT, UPDATE ON TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW
    TO ROLE EFNS_DEV_APP_OWNER;
-- Apply sql/17_Historical_Manual_Corrections.sql before deploying the manual editor.
GRANT SELECT, INSERT ON TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_DECISION
    TO ROLE EFNS_DEV_APP_OWNER;

GRANT USAGE ON DATABASE EFNS_DEV TO ROLE EFNS_DEV_ADMIN;
GRANT USAGE ON DATABASE EFNS_DEV TO ROLE EFNS_DEV_EDITOR;
GRANT USAGE ON DATABASE EFNS_DEV TO ROLE EFNS_DEV_DEVELOPER;
GRANT USAGE ON DATABASE EFNS_DEV TO ROLE EFNS_DEV_VIEWER;

GRANT USAGE ON SCHEMA EFNS_DEV.APP TO ROLE EFNS_DEV_ADMIN;
GRANT USAGE ON SCHEMA EFNS_DEV.APP TO ROLE EFNS_DEV_EDITOR;
GRANT USAGE ON SCHEMA EFNS_DEV.APP TO ROLE EFNS_DEV_DEVELOPER;
GRANT USAGE ON SCHEMA EFNS_DEV.APP TO ROLE EFNS_DEV_VIEWER;

GRANT USAGE ON STREAMLIT EFNS_DEV.APP.EFNS_INTERNAL_APP TO ROLE EFNS_DEV_ADMIN;
GRANT USAGE ON STREAMLIT EFNS_DEV.APP.EFNS_INTERNAL_APP TO ROLE EFNS_DEV_EDITOR;
GRANT USAGE ON STREAMLIT EFNS_DEV.APP.EFNS_INTERNAL_APP TO ROLE EFNS_DEV_DEVELOPER;
GRANT USAGE ON STREAMLIT EFNS_DEV.APP.EFNS_INTERNAL_APP TO ROLE EFNS_DEV_VIEWER;

-- Additive company DEV upgrade. No business/import rows are changed.
-- The same table/columns are included in the fresh-company schema builder.
USE ROLE ACCOUNTADMIN;
USE DATABASE EFNS_DEV;
USE WAREHOUSE EFNS_DEV_WH;
EXECUTE IMMEDIATE $$
DECLARE wrong_target EXCEPTION (-20017,'Expected company EFNS_DEV');
BEGIN
 IF (CURRENT_ORGANIZATION_NAME()<>'QDCTNKN' OR CURRENT_ACCOUNT_NAME()<>'UW19058'
     OR CURRENT_ACCOUNT()<>'CB12755' OR CURRENT_REGION()<>'AWS_CA_CENTRAL_1'
     OR CURRENT_DATABASE()<>'EFNS_DEV') THEN
  RAISE wrong_target;
 END IF;
 CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_DECISION (
  DECISION_ID VARCHAR(36) NOT NULL,
  ORIGINAL_MIGRATION_BATCH_ID VARCHAR(64) NOT NULL,
  MIGRATION_RAW_ROW_ID VARCHAR(64) NOT NULL,
  SOURCE_ENTITY VARCHAR(100) NOT NULL,
  VERSION NUMBER(18,0) NOT NULL,
  REQUEST_ID VARCHAR(128) NOT NULL,
  CHANGES VARIANT NOT NULL,
  BEFORE_DATA VARIANT NOT NULL,
  AFTER_DATA VARIANT NOT NULL,
  BASIS VARCHAR(2000) NOT NULL,
  ACTOR_EMAIL VARCHAR(320) NOT NULL,
  STATUS VARCHAR(30) NOT NULL DEFAULT 'SAVED',
  -- The writer supplies server UTC explicitly; client timestamps are never bound.
  RECORDED_AT TIMESTAMP_NTZ NOT NULL,
  CONSTRAINT PK_MIGRATION_CORRECTION_DECISION PRIMARY KEY (DECISION_ID),
  CONSTRAINT UQ_MIGRATION_CORRECTION_DECISION_VERSION UNIQUE (ORIGINAL_MIGRATION_BATCH_ID,MIGRATION_RAW_ROW_ID,VERSION),
  CONSTRAINT FK_MANUAL_CORRECTION_RAW FOREIGN KEY (ORIGINAL_MIGRATION_BATCH_ID,MIGRATION_RAW_ROW_ID)
   REFERENCES EFNS_DEV.RAW.MIGRATION_RAW_ROW(MIGRATION_BATCH_ID,MIGRATION_RAW_ROW_ID)
 );
 ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW ADD COLUMN IF NOT EXISTS DECISION_ID VARCHAR(36);
 ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW ADD COLUMN IF NOT EXISTS DECISION_VERSION NUMBER(18,0);
 GRANT SELECT,INSERT ON TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_DECISION TO ROLE EFNS_DEV_APP_OWNER;
 -- No UPDATE/DELETE or future-object grants. Decisions are append-only.
END;
$$;
SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,IS_NULLABLE FROM EFNS_DEV.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA='RAW' AND TABLE_NAME IN ('MIGRATION_CORRECTION_DECISION','MIGRATION_CORRECTION_ROW')
ORDER BY TABLE_NAME,ORDINAL_POSITION;
SHOW GRANTS ON TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_DECISION;
SHOW PRIMARY KEYS IN TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_DECISION;
SHOW IMPORTED KEYS IN TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_DECISION;

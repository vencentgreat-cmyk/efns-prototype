ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_BATCH ADD COLUMN IF NOT EXISTS COMMITTED_AT TIMESTAMP_NTZ;
ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_BATCH ADD COLUMN IF NOT EXISTS CREATED_AT TIMESTAMP_NTZ;
ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_BATCH ADD COLUMN IF NOT EXISTS UPDATED_AT TIMESTAMP_NTZ;

ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW ADD COLUMN IF NOT EXISTS MIGRATION_CORRECTION_ROW_ID VARCHAR(36);
ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW ADD COLUMN IF NOT EXISTS MIGRATION_CORRECTION_BATCH_ID VARCHAR(128);
ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW ADD COLUMN IF NOT EXISTS ORIGINAL_MIGRATION_BATCH_ID VARCHAR(64);
ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW ADD COLUMN IF NOT EXISTS MIGRATION_RAW_ROW_ID VARCHAR(64);
ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW ADD COLUMN IF NOT EXISTS SOURCE_FILENAME VARCHAR(500);
ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW ADD COLUMN IF NOT EXISTS SOURCE_ENTITY VARCHAR(100);

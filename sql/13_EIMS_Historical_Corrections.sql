USE ROLE SECURITYADMIN;
GRANT SELECT, INSERT, UPDATE ON TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_BATCH TO ROLE EFNS_DEV_APP_OWNER;
GRANT SELECT, INSERT, UPDATE ON TABLE EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW TO ROLE EFNS_DEV_APP_OWNER;

USE ROLE ACCOUNTADMIN;
USE DATABASE EFNS_DEV;

SELECT TABLE_SCHEMA, TABLE_NAME
FROM EFNS_DEV.INFORMATION_SCHEMA.TABLES
WHERE (TABLE_SCHEMA, TABLE_NAME) IN (
    ('RAW', 'MIGRATION_CORRECTION_BATCH'),
    ('RAW', 'MIGRATION_CORRECTION_ROW')
)
ORDER BY TABLE_SCHEMA, TABLE_NAME;

SELECT TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, DATA_TYPE, IS_NULLABLE
FROM EFNS_DEV.INFORMATION_SCHEMA.COLUMNS
WHERE (TABLE_SCHEMA = 'CORE' AND TABLE_NAME = 'QUOTA_REGISTRATION' AND COLUMN_NAME = 'REGISTRATION_NUMBER')
   OR (TABLE_SCHEMA = 'RAW' AND TABLE_NAME IN ('MIGRATION_CORRECTION_BATCH', 'MIGRATION_CORRECTION_ROW'))
ORDER BY TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION;

SELECT IFF(
    (SELECT IS_NULLABLE FROM EFNS_DEV.INFORMATION_SCHEMA.COLUMNS
     WHERE TABLE_SCHEMA = 'CORE' AND TABLE_NAME = 'QUOTA_REGISTRATION'
       AND COLUMN_NAME = 'REGISTRATION_NUMBER') = 'YES'
    AND (SELECT COUNT(*) FROM EFNS_DEV.INFORMATION_SCHEMA.TABLES
         WHERE TABLE_SCHEMA = 'RAW'
           AND TABLE_NAME IN ('MIGRATION_CORRECTION_BATCH', 'MIGRATION_CORRECTION_ROW')) = 2,
    'READY_FOR_HISTORICAL_CORRECTION_PREVIEW',
    'NOT_READY'
) AS FINAL_STATUS;

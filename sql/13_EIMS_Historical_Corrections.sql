ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_BATCH ADD COLUMN IF NOT EXISTS ORIGINAL_MIGRATION_BATCH_ID VARCHAR(64);
ALTER TABLE IF EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_BATCH ADD COLUMN IF NOT EXISTS STATUS VARCHAR(30);

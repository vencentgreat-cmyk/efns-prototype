-- Additive DEV-only support for confirmed historical EIMS corrections.
-- This script does not update migration rows or import business data.

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE EFNS_DEV_WH;
USE DATABASE EFNS_DEV;

SELECT CURRENT_ROLE(), CURRENT_WAREHOUSE(), CURRENT_DATABASE(), CURRENT_SCHEMA();

EXECUTE IMMEDIATE $$
DECLARE
    WRONG_DATABASE EXCEPTION (-20013, 'Historical correction DDL is restricted to EFNS_DEV.');
BEGIN
    IF (CURRENT_DATABASE() IS NULL OR UPPER(CURRENT_DATABASE()) <> 'EFNS_DEV') THEN
        RAISE WRONG_DATABASE;
    END IF;
END;
$$;

EXECUTE IMMEDIATE $$
BEGIN
    IF (EXISTS (
        SELECT 1
        FROM EFNS_DEV.INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA = 'CORE'
          AND TABLE_NAME = 'QUOTA_REGISTRATION'
          AND COLUMN_NAME = 'REGISTRATION_NUMBER'
          AND IS_NULLABLE = 'NO'
    )) THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE EFNS_DEV.CORE.QUOTA_REGISTRATION ALTER COLUMN REGISTRATION_NUMBER DROP NOT NULL';
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_BATCH (
    MIGRATION_CORRECTION_BATCH_ID VARCHAR(128) NOT NULL,
    ORIGINAL_MIGRATION_BATCH_ID VARCHAR(64) NOT NULL,
    STATUS VARCHAR(30) NOT NULL,
    READY_ROW_COUNT NUMBER(18,0) NOT NULL DEFAULT 0,
    PENDING_ROW_COUNT NUMBER(18,0) NOT NULL DEFAULT 0,
    COMMITTED_AT TIMESTAMP_NTZ,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_MIGRATION_CORRECTION_BATCH PRIMARY KEY (MIGRATION_CORRECTION_BATCH_ID),
    CONSTRAINT FK_MIGRATION_CORRECTION_ORIGINAL_BATCH FOREIGN KEY (ORIGINAL_MIGRATION_BATCH_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_BATCH (MIGRATION_BATCH_ID)
);

CREATE TABLE IF NOT EXISTS EFNS_DEV.RAW.MIGRATION_CORRECTION_ROW (
    MIGRATION_CORRECTION_ROW_ID VARCHAR(36) NOT NULL,
    MIGRATION_CORRECTION_BATCH_ID VARCHAR(128) NOT NULL,
    ORIGINAL_MIGRATION_BATCH_ID VARCHAR(64) NOT NULL,
    MIGRATION_RAW_ROW_ID VARCHAR(64) NOT NULL,
    SOURCE_FILENAME VARCHAR(500) NOT NULL,
    SOURCE_ENTITY VARCHAR(100) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER(18,0) NOT NULL,
    SOURCE_ID VARCHAR(255),
    TARGET_ID VARCHAR(255),
    DISPOSITION VARCHAR(30) NOT NULL,
    RELATION_STATUS VARCHAR(30) NOT NULL,
    REASON VARCHAR(2000) NOT NULL,
    CORRECTED_DATA VARIANT,
    CREATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_MIGRATION_CORRECTION_ROW PRIMARY KEY (MIGRATION_CORRECTION_ROW_ID),
    CONSTRAINT FK_MIGRATION_CORRECTION_ROW_BATCH FOREIGN KEY (MIGRATION_CORRECTION_BATCH_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_CORRECTION_BATCH (MIGRATION_CORRECTION_BATCH_ID),
    CONSTRAINT FK_MIGRATION_CORRECTION_ROW_ORIGINAL_BATCH FOREIGN KEY (ORIGINAL_MIGRATION_BATCH_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_BATCH (MIGRATION_BATCH_ID),
    CONSTRAINT FK_MIGRATION_CORRECTION_RAW_ROW FOREIGN KEY (ORIGINAL_MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID)
        REFERENCES EFNS_DEV.RAW.MIGRATION_RAW_ROW (MIGRATION_BATCH_ID, MIGRATION_RAW_ROW_ID),
    CONSTRAINT UQ_MIGRATION_CORRECTION_RAW_ROW UNIQUE (MIGRATION_CORRECTION_BATCH_ID, MIGRATION_RAW_ROW_ID)
);


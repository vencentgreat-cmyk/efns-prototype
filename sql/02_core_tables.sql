CREATE TABLE IF NOT EXISTS EFNS_DEV.CORE.QUOTA_REGISTRATION (
    QUOTA_ID VARCHAR(36) NOT NULL,
    REGISTRATION_NUMBER VARCHAR(64) NOT NULL,
    ACCOUNT_ID VARCHAR(36) NOT NULL,
    QUOTA_NAME VARCHAR(255),
    QUOTA_TYPE VARCHAR(100) NOT NULL,
    STATUS VARCHAR(30) DEFAULT 'Active',
    EFFECTIVE_DATE DATE,
    END_DATE DATE,
    COMMENTS VARCHAR(2000),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_QUOTA_REGISTRATION PRIMARY KEY (QUOTA_ID),
    CONSTRAINT FK_QUOTA_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
        REFERENCES EFNS_DEV.CORE.ACCOUNT (ACCOUNT_ID)
)
COMMENT = 'Quota allocation model and choice values are provisional.';

CREATE TABLE IF NOT EXISTS EFNS_DEV.CORE.FLOCK (
    FLOCK_ID VARCHAR(36) NOT NULL,
    FLOCK_NUMBER VARCHAR(64) NOT NULL,
    ACCOUNT_ID VARCHAR(36) NOT NULL,
    FACILITY_ID VARCHAR(36) NOT NULL,
    FACILITY_DETAIL_ID VARCHAR(36),
    QUOTA_ID VARCHAR(36),
    FLOCK_QUOTA_TYPE VARCHAR(100),
    STATUS VARCHAR(30) DEFAULT 'Planned',
    CREATE_DELIVERY_TRANSACTION BOOLEAN DEFAULT FALSE,
    PERMIT_NUMBER VARCHAR(100) NOT NULL,
    PERMIT_DATE DATE,
    HATCH_DATE DATE NOT NULL,
    DATE_ORDERED DATE,
    BIRD_COUNT NUMBER(12,0) NOT NULL,
    EGG_COLOUR VARCHAR(50),
    BIRD_STRAIN VARCHAR(100),
    PLACEMENT_DATE DATE,
    EST_DISPOSAL DATE,
    DISPOSAL_DATE DATE,
    BIRDS_DISPOSED NUMBER(12,0) DEFAULT 0,
    BREEDER VARCHAR(255),
    HATCHERY VARCHAR(255),
    PULLET_GROWER VARCHAR(255),
    DISPOSAL_PLANT VARCHAR(255),
    DISPOSAL_METHOD VARCHAR(100),
    COMMENTS VARCHAR(2000),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_FLOCK PRIMARY KEY (FLOCK_ID),
    CONSTRAINT FK_FLOCK_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
        REFERENCES EFNS_DEV.CORE.ACCOUNT (ACCOUNT_ID),
    CONSTRAINT FK_FLOCK_FACILITY FOREIGN KEY (FACILITY_ID)
        REFERENCES EFNS_DEV.CORE.FACILITY (FACILITY_ID),
    CONSTRAINT FK_FLOCK_DETAIL FOREIGN KEY (FACILITY_DETAIL_ID)
        REFERENCES EFNS_DEV.CORE.FACILITY_DETAIL (FACILITY_DETAIL_ID),
    CONSTRAINT FK_FLOCK_QUOTA FOREIGN KEY (QUOTA_ID)
        REFERENCES EFNS_DEV.CORE.QUOTA_REGISTRATION (QUOTA_ID),
    CONSTRAINT CK_FLOCK_BIRD_COUNT CHECK (BIRD_COUNT >= 0),
    CONSTRAINT CK_FLOCK_BIRDS_DISPOSED CHECK (BIRDS_DISPOSED >= 0)
);

CREATE TABLE IF NOT EXISTS EFNS_DEV.CORE.FLOCK_TRANSACTION (
    FLOCK_TRANSACTION_ID VARCHAR(36) NOT NULL,
    FLOCK_ID VARCHAR(36) NOT NULL,
    TRANSACTION_TYPE VARCHAR(100) NOT NULL,
    QUANTITY NUMBER(12,2) NOT NULL,
    TRANSACTION_DATE DATE NOT NULL,
    NOTES VARCHAR(2000),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_FLOCK_TRANSACTION PRIMARY KEY (FLOCK_TRANSACTION_ID),
    CONSTRAINT FK_FLOCK_TRANSACTION_FLOCK FOREIGN KEY (FLOCK_ID)
        REFERENCES EFNS_DEV.CORE.FLOCK (FLOCK_ID),
    CONSTRAINT CK_FLOCK_TRANSACTION_QUANTITY CHECK (QUANTITY > 0)
);

CREATE TABLE IF NOT EXISTS EFNS_DEV.CORE.QUOTA_TRANSACTION (
    QUOTA_TRANSACTION_ID VARCHAR(36) NOT NULL,
    TRANSACTION_TYPE VARCHAR(50) NOT NULL,
    QUOTA_ID VARCHAR(36) NOT NULL,
    EFFECTIVE_DATE DATE NOT NULL,
    END_DATE DATE,
    QUOTA_COUNT NUMBER(14,2) NOT NULL,
    OWNER_ACCOUNT_ID VARCHAR(36) NOT NULL,
    RELATED_ACCOUNT_ID VARCHAR(36) NOT NULL,
    RELATED_QUOTA_ID VARCHAR(36),
    RELATED_TRANSACTION_ID VARCHAR(36),
    PRICE NUMBER(14,2),
    QUOTA_LEASE_TYPE VARCHAR(100),
    COMMENTS VARCHAR(2000),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_QUOTA_TRANSACTION PRIMARY KEY (QUOTA_TRANSACTION_ID),
    CONSTRAINT FK_QUOTA_TRANSACTION_QUOTA FOREIGN KEY (QUOTA_ID)
        REFERENCES EFNS_DEV.CORE.QUOTA_REGISTRATION (QUOTA_ID),
    CONSTRAINT FK_QUOTA_TRANSACTION_OWNER FOREIGN KEY (OWNER_ACCOUNT_ID)
        REFERENCES EFNS_DEV.CORE.ACCOUNT (ACCOUNT_ID),
    CONSTRAINT FK_QUOTA_TRANSACTION_RELATED_ACCOUNT FOREIGN KEY (RELATED_ACCOUNT_ID)
        REFERENCES EFNS_DEV.CORE.ACCOUNT (ACCOUNT_ID),
    CONSTRAINT CK_QUOTA_TRANSACTION_COUNT CHECK (QUOTA_COUNT > 0)
)
COMMENT = 'Activity records only; no automatic quota balance calculation.';


    CONSTRUCTION_DATE DATE,
    CLOSURE_DATE DATE,
    DESTRUCTION_DATE DATE,
    INACTIVE_DATE DATE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_FACILITY PRIMARY KEY (FACILITY_ID),
    CONSTRAINT FK_FACILITY_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
        REFERENCES EFNS_DEV.CORE.ACCOUNT (ACCOUNT_ID)
);

CREATE TABLE IF NOT EXISTS EFNS_DEV.CORE.FACILITY_DETAIL (

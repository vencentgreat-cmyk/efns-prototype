-- EFNS DEV / PROVISIONAL core schema
-- Repeatable for a fresh or already-aligned DEV database. Existing legacy
-- schemas require a reviewed migration before this definition is applied.

CREATE TABLE IF NOT EXISTS EFNS_DEV.CORE.ACCOUNT (
    ACCOUNT_ID VARCHAR(36) NOT NULL,
    REGISTRATION_NUMBER VARCHAR(64),
    ORGANIZATION_NAME VARCHAR(255) NOT NULL,
    ADDRESS_LINE1 VARCHAR(255),
    ADDRESS_LINE2 VARCHAR(255),
    ADDRESS_LINE3 VARCHAR(255),
    CITY VARCHAR(100),
    PROVINCE VARCHAR(50),
    POSTAL_CODE VARCHAR(20),
    COUNTRY_REGION VARCHAR(100),
    LATITUDE NUMBER(10,7),
    LONGITUDE NUMBER(10,7),
    CONTACT_NAME VARCHAR(255),
    CONTACT_PHONE VARCHAR(50),
    CONTACT_EMAIL VARCHAR(255),
    FAX VARCHAR(50),
    WEBSITE VARCHAR(500),
    LICENCE_NUMBER VARCHAR(64),
    PARENT_ACCOUNT_ID VARCHAR(36),
    GRADING_STATION_ACCOUNT_ID VARCHAR(36),
    PULLET_GROWER_ACCOUNT_ID VARCHAR(36),
    PROVINCE_OF_REGISTRATION VARCHAR(50),
    SPENT_FOWL_PLANS VARCHAR(2000),
    DEFAULT_ON_REPORTS BOOLEAN DEFAULT FALSE,
    NO_SVG BOOLEAN DEFAULT FALSE,
    DESCRIPTION VARCHAR(4000),
    PRODUCER_ROLE BOOLEAN DEFAULT FALSE,
    BREEDER_ROLE BOOLEAN DEFAULT FALSE,
    HATCHERY_ROLE BOOLEAN DEFAULT FALSE,
    PULLET_GROWER_ROLE BOOLEAN DEFAULT FALSE,
    GRADER_ROLE BOOLEAN DEFAULT FALSE,
    PROCESSOR_BREAKER_ROLE BOOLEAN DEFAULT FALSE,
    DISPOSAL_PLANT_ROLE BOOLEAN DEFAULT FALSE,
    UNREGULATED_ROLE BOOLEAN DEFAULT FALSE,
    PROV_BOARD_EFC_ROLE BOOLEAN DEFAULT FALSE,
    GOVERNMENT_ROLE BOOLEAN DEFAULT FALSE,
    VENDOR_ROLE BOOLEAN DEFAULT FALSE,
    RESEARCH_EXEMPT_ROLE BOOLEAN DEFAULT FALSE,
    SHIPPER_ROLE BOOLEAN DEFAULT FALSE,
    OTHER_ROLE BOOLEAN DEFAULT FALSE,
    STATUS VARCHAR(30) DEFAULT 'Active',
    CREATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_ACCOUNT PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT FK_ACCOUNT_PARENT FOREIGN KEY (PARENT_ACCOUNT_ID)
        REFERENCES EFNS_DEV.CORE.ACCOUNT (ACCOUNT_ID),
    CONSTRAINT FK_ACCOUNT_GRADING_STATION FOREIGN KEY (GRADING_STATION_ACCOUNT_ID)
        REFERENCES EFNS_DEV.CORE.ACCOUNT (ACCOUNT_ID),
    CONSTRAINT FK_ACCOUNT_PULLET_GROWER FOREIGN KEY (PULLET_GROWER_ACCOUNT_ID)
        REFERENCES EFNS_DEV.CORE.ACCOUNT (ACCOUNT_ID)
)
COMMENT = 'DEV/provisional account model; Dataverse logical names are not confirmed.';

-- Dynamics labels this area "Other Addresses" and the view "Farm Locations".
-- This provisional child remains separate from regulated FACILITY records.
CREATE TABLE IF NOT EXISTS EFNS_DEV.CORE.FARM_LOCATION (
    FARM_LOCATION_ID VARCHAR(36) NOT NULL,
    ACCOUNT_ID VARCHAR(36) NOT NULL,
    LOCATION_NAME VARCHAR(255) NOT NULL,
    ADDRESS_1 VARCHAR(255),
    ADDRESS_2 VARCHAR(255),
    CITY VARCHAR(100),
    PROVINCE VARCHAR(50),
    POSTAL_CODE VARCHAR(20),
    PHONE VARCHAR(50),
    STATUS VARCHAR(30) DEFAULT 'Active',
    CREATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ,
    CONSTRAINT PK_FARM_LOCATION PRIMARY KEY (FARM_LOCATION_ID),
    CONSTRAINT FK_FARM_LOCATION_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
        REFERENCES EFNS_DEV.CORE.ACCOUNT (ACCOUNT_ID)
)
COMMENT = 'DEV/provisional Account-owned Farm Location (Dynamics Other Address); distinct from Facility.';

CREATE TABLE IF NOT EXISTS EFNS_DEV.CORE.FACILITY (
    FACILITY_ID VARCHAR(36) NOT NULL,

-- Additive COMPANY DEV upgrade only. No archive, batch or business DML.
USE ROLE ACCOUNTADMIN;
USE DATABASE EFNS_DEV;
USE WAREHOUSE EFNS_DEV_WH;
SELECT CURRENT_ORGANIZATION_NAME(),CURRENT_ACCOUNT_NAME(),CURRENT_ACCOUNT(),CURRENT_DATABASE();
EXECUTE IMMEDIATE $$
DECLARE
 wrong_target EXCEPTION (-20018,'Expected company EFNS_DEV and one existing continuity lock row');
BEGIN
 IF (CURRENT_ORGANIZATION_NAME()<>'QDCTNKN' OR CURRENT_ACCOUNT_NAME()<>'UW19058'
     OR CURRENT_ACCOUNT()<>'CB12755' OR CURRENT_REGION()<>'AWS_CA_CENTRAL_1'
     OR CURRENT_DATABASE()<>'EFNS_DEV') THEN
  RAISE wrong_target;
 END IF;
 IF ((SELECT COUNT(*) FROM EFNS_DEV.RAW.INTAKE_LOCK WHERE LOCK_ID='continuity')<>1) THEN
  RAISE wrong_target;
 END IF;
 ALTER TABLE EFNS_DEV.CORE.FLOCK_TRANSACTION ADD COLUMN IF NOT EXISTS COUNT_SOURCE_LABEL VARCHAR(255);
 GRANT SELECT,INSERT ON TABLE EFNS_DEV.CORE.FLOCK_TRANSACTION TO ROLE EFNS_DEV_APP_OWNER;
 GRANT SELECT ON TABLE EFNS_DEV.CORE.FLOCK TO ROLE EFNS_DEV_APP_OWNER;
 GRANT SELECT ON TABLE EFNS_DEV.CORE.ACCOUNT TO ROLE EFNS_DEV_APP_OWNER;
 GRANT SELECT ON TABLE EFNS_DEV.CORE.FACILITY TO ROLE EFNS_DEV_APP_OWNER;
 GRANT SELECT ON TABLE EFNS_DEV.RAW.MIGRATION_BATCH TO ROLE EFNS_DEV_APP_OWNER;
 GRANT SELECT ON TABLE EFNS_DEV.RAW.MIGRATION_RAW_ROW TO ROLE EFNS_DEV_APP_OWNER;
 GRANT SELECT ON TABLE EFNS_DEV.RAW.MIGRATION_ID_MAP TO ROLE EFNS_DEV_APP_OWNER;
 GRANT SELECT,INSERT ON TABLE EFNS_DEV.RAW.IMPORT_BATCH TO ROLE EFNS_DEV_APP_OWNER;
 GRANT SELECT,INSERT ON TABLE EFNS_DEV.RAW.IMPORT_RAW_ROW TO ROLE EFNS_DEV_APP_OWNER;
 GRANT SELECT,INSERT ON TABLE EFNS_DEV.RAW.SOURCE_FILE TO ROLE EFNS_DEV_APP_OWNER;
 GRANT SELECT,UPDATE ON TABLE EFNS_DEV.RAW.INTAKE_LOCK TO ROLE EFNS_DEV_APP_OWNER;
 GRANT INSERT ON TABLE EFNS_DEV.APP.AUDIT_EVENT TO ROLE EFNS_DEV_APP_OWNER;
 GRANT READ,WRITE ON STAGE EFNS_DEV.RAW.EIMS_MIGRATION_FILES TO ROLE EFNS_DEV_APP_OWNER;
END;
$$;
SELECT COLUMN_NAME,DATA_TYPE,CHARACTER_MAXIMUM_LENGTH,IS_NULLABLE,COLUMN_DEFAULT
FROM EFNS_DEV.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA='CORE' AND TABLE_NAME='FLOCK_TRANSACTION' AND COLUMN_NAME='COUNT_SOURCE_LABEL';
SHOW GRANTS ON TABLE EFNS_DEV.CORE.FLOCK_TRANSACTION;
SHOW GRANTS ON TABLE EFNS_DEV.RAW.INTAKE_LOCK;

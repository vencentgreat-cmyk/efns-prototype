-- C. Production summary: exact ID coverage, not just equal table counts.
WITH core_keys AS (SELECT PRODUCTION_ID, COUNT(*) AS N FROM EFNS_DEV.CORE.PRODUCTION_RECORD GROUP BY PRODUCTION_ID),
view_keys AS (SELECT PRODUCTION_ID, COUNT(*) AS N FROM EFNS_DEV.REPORTING.VW_PRODUCTION_SUMMARY GROUP BY PRODUCTION_ID)
SELECT COALESCE(COUNT_IF(c.PRODUCTION_ID IS NOT NULL AND v.PRODUCTION_ID IS NULL),0) AS MISSING_IDS,
       COALESCE(COUNT_IF(c.PRODUCTION_ID IS NULL AND v.PRODUCTION_ID IS NOT NULL),0) AS EXTRA_IDS,
       COALESCE(COUNT_IF(c.N IS DISTINCT FROM v.N),0) AS MULTIPLICITY_MISMATCHES
FROM core_keys c FULL OUTER JOIN view_keys v ON c.PRODUCTION_ID = v.PRODUCTION_ID;

SELECT COALESCE(COUNT_IF(v.REPORTING_YEAR IS DISTINCT FROM p.REPORTING_YEAR
    OR v.REPORTING_WEEK IS DISTINCT FROM p.REPORTING_WEEK),0) AS PERIOD_MISMATCH_ROWS
FROM EFNS_DEV.REPORTING.VW_PRODUCTION_SUMMARY v
JOIN EFNS_DEV.CORE.PRODUCTION_RECORD p ON p.PRODUCTION_ID = v.PRODUCTION_ID;

-- Known row periods survive even without an Import Batch. Group output contains no PII.
SELECT p.REPORTING_YEAR, p.REPORTING_WEEK, COUNT(*) AS CORE_ROW_COUNT,
       COUNT(v.PRODUCTION_ID) AS VIEW_ROW_COUNT
FROM EFNS_DEV.CORE.PRODUCTION_RECORD p
LEFT JOIN EFNS_DEV.RAW.IMPORT_BATCH b ON p.IMPORT_ID = b.IMPORT_ID
LEFT JOIN EFNS_DEV.REPORTING.VW_PRODUCTION_SUMMARY v ON p.PRODUCTION_ID = v.PRODUCTION_ID
WHERE b.IMPORT_ID IS NULL
GROUP BY p.REPORTING_YEAR, p.REPORTING_WEEK;


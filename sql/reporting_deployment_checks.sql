-- Size-grain verification:
-- One row per actual child, OR one null-child placeholder per production without sizes.
WITH children AS (
    SELECT PRODUCTION_ID, COUNT(*) AS N
    FROM EFNS_DEV.CORE.PRODUCTION_SIZE_BREAKDOWN GROUP BY PRODUCTION_ID
)
SELECT COUNT(*) AS PRODUCTION_COUNT,
       COALESCE(COUNT_IF(c.N > 0),0) AS PRODUCTIONS_WITH_SIZES,
       COALESCE(COUNT_IF(c.N IS NULL),0) AS PRODUCTIONS_WITHOUT_SIZES,
       SUM(COALESCE(c.N,1)) AS EXPECTED_SIZE_VIEW_ROWS,
       (SELECT COUNT(*) FROM EFNS_DEV.REPORTING.VW_PRODUCTION_SIZE_DETAIL) AS ACTUAL_SIZE_VIEW_ROWS
FROM EFNS_DEV.CORE.PRODUCTION_RECORD p LEFT JOIN children c ON p.PRODUCTION_ID = c.PRODUCTION_ID;

WITH expected AS (
    SELECT p.PRODUCTION_ID, s.SIZE_BREAKDOWN_ID, COUNT(*) AS N
    FROM EFNS_DEV.CORE.PRODUCTION_RECORD p
    LEFT JOIN EFNS_DEV.CORE.PRODUCTION_SIZE_BREAKDOWN s ON p.PRODUCTION_ID = s.PRODUCTION_ID
    GROUP BY p.PRODUCTION_ID, s.SIZE_BREAKDOWN_ID
), actual AS (
    SELECT PRODUCTION_ID, SIZE_BREAKDOWN_ID, COUNT(*) AS N
    FROM EFNS_DEV.REPORTING.VW_PRODUCTION_SIZE_DETAIL GROUP BY PRODUCTION_ID, SIZE_BREAKDOWN_ID
)
SELECT COALESCE(COUNT_IF(e.N IS DISTINCT FROM a.N),0) AS SIZE_GRAIN_MISMATCHES,
       COALESCE(COUNT_IF(e.N IS NOT NULL AND a.N IS NULL AND e.SIZE_BREAKDOWN_ID IS NULL),0) AS MISSING_NO_SIZE_PLACEHOLDERS,
       COALESCE(COUNT_IF(e.N IS NOT NULL AND a.N IS NULL AND e.SIZE_BREAKDOWN_ID IS NOT NULL),0) AS MISSING_SIZE_RECORDS,
       COALESCE(COUNT_IF(e.N IS NULL AND a.N IS NOT NULL),0) AS EXTRA_SIZE_VIEW_RECORDS
FROM expected e FULL OUTER JOIN actual a
  ON e.PRODUCTION_ID = a.PRODUCTION_ID
 AND e.SIZE_BREAKDOWN_ID IS NOT DISTINCT FROM a.SIZE_BREAKDOWN_ID;

SELECT COALESCE(COUNT_IF(v.REPORTING_YEAR IS DISTINCT FROM p.REPORTING_YEAR
    OR v.REPORTING_WEEK IS DISTINCT FROM p.REPORTING_WEEK),0) AS SIZE_PERIOD_MISMATCHES,
       COALESCE(COUNT_IF(v.SIZE_BREAKDOWN_ID IS NOT NULL AND
           (v.QUANTITY IS DISTINCT FROM s.QUANTITY OR v.SIZE_BAND IS DISTINCT FROM s.SIZE_BAND)),0) AS SIZE_VALUE_MISMATCHES
FROM EFNS_DEV.REPORTING.VW_PRODUCTION_SIZE_DETAIL v
JOIN EFNS_DEV.CORE.PRODUCTION_RECORD p ON p.PRODUCTION_ID = v.PRODUCTION_ID
LEFT JOIN EFNS_DEV.CORE.PRODUCTION_SIZE_BREAKDOWN s ON s.SIZE_BREAKDOWN_ID = v.SIZE_BREAKDOWN_ID;

SELECT COUNT(*) AS ORPHAN_SIZE_RECORDS
FROM EFNS_DEV.CORE.PRODUCTION_SIZE_BREAKDOWN s
LEFT JOIN EFNS_DEV.CORE.PRODUCTION_RECORD p ON s.PRODUCTION_ID = p.PRODUCTION_ID
WHERE p.PRODUCTION_ID IS NULL;

-- Compare quantities only at size-record grain, including negative quantities.
SELECT c.NON_NULL_COUNT AS CORE_SIZE_NON_NULL, v.NON_NULL_COUNT AS VIEW_SIZE_NON_NULL,
       c.AMOUNT AS CORE_SIZE_QUANTITY, v.AMOUNT AS VIEW_SIZE_QUANTITY,
       c.NEG AS CORE_SIZE_NEGATIVE_ROWS, v.NEG AS VIEW_SIZE_NEGATIVE_ROWS
FROM (SELECT COUNT(s.QUANTITY) AS NON_NULL_COUNT, SUM(s.QUANTITY) AS AMOUNT,
             COALESCE(COUNT_IF(s.QUANTITY < 0),0) AS NEG
      FROM EFNS_DEV.CORE.PRODUCTION_SIZE_BREAKDOWN s
      JOIN EFNS_DEV.CORE.PRODUCTION_RECORD p ON p.PRODUCTION_ID = s.PRODUCTION_ID) c
CROSS JOIN (SELECT COUNT(QUANTITY) AS NON_NULL_COUNT, SUM(QUANTITY) AS AMOUNT,
                   COALESCE(COUNT_IF(QUANTITY < 0),0) AS NEG
            FROM EFNS_DEV.REPORTING.VW_PRODUCTION_SIZE_DETAIL WHERE SIZE_BREAKDOWN_ID IS NOT NULL) v;

